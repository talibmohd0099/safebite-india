/**
 * Resolves a barcode's leading digits to a GS1 country/range entry.
 * @param {string} barcodeDigits - the raw barcode (any length; only the
 *   first 3 digits matter for this lookup)
 * @returns {{ label: string, type: 'india'|'country'|'restricted'|'domestic-other'|'other'|'unknown' }}
 */
export function resolveGs1Prefix(barcodeDigits) {
  const clean = (barcodeDigits || '').replace(/\D/g, '');
  if (clean.length < 3) return { label: 'Too short to resolve', type: 'unknown' };
  const prefix3 = parseInt(clean.slice(0, 3), 10);
  const range = GS1_PREFIX_RANGES.find((r) => prefix3 >= r.min && prefix3 <= r.max);
  return range ? { label: range.label, type: range.type } : { label: 'Unassigned prefix', type: 'unknown' };
}
